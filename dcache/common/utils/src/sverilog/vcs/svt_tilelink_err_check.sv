/**
 * Derived sampling and checking class used by Tilelink MASTER components to 
 * register layer wide checks.
 */
class svt_tilelink_err_check extends svt_err_check;

  // ****************************************************************************
  // Local Data
  // ****************************************************************************

// vb_preserve TMPL_TAG1
  //  ADD MASTER SPECIFIC GROUPS AND SUB-GROUPS HERE
  // vb_preserve end
  /**
   * The group name of the checks defined in this class.
   */
  local string group_name = "COMMON CHECKS";
