    /**
     * Check: Before deasserting reset, a_valid, c_valid, and e_valid must be driven LOW by the master, while b_valid and d_valid must be driven LOW by the slave.
     */
    svt_err_check_stats valid_values_in_reset_error;

    /**
     * Check: The valid signals must be driven LOW for at least 100 cycles while reset is asserted.
     */
    svt_err_check_stats valid_signal_duration_in_reset_error;

    /**
     * Check: The valid signals may be driven HIGH only after the first rising edge of clock where reset is LOW.
     */
    svt_err_check_stats valid_assertion_post_reset_error;

    /**
     * Check: "Once a burst has begun, the sender must not send beats for any other message until the last beat of the burst has been accepted by the receiver.
     */
    svt_err_check_stats no_intrlv_support_error;

    /**
     * Check: When a burst is in progress, if valid is HIGH, the sender must present control signals identical to those of the first beat.
     */
    svt_err_check_stats burst_ctrl_sig_value_error;

    /**
     * Check: The first beat of the response message must be presented no earlier than the first beat of the request message.
     */
    svt_err_check_stats resp_wo_req_error;

    /**
     * Check: The first beat of the response(GrantAck) message must be presented no earlier than the first beat of the request message(Grant/GrantData).
     */
    svt_err_check_stats unknown_e_sink_error;

    /**
     * Check: On channels A and B, which carry a mask field, the mask must always be LOW for all inactive byte lanes.
     */
    svt_err_check_stats invalid_mask_val_error;

    /**
     * Check: Get messages are never multi-beat, but must still drive mask HIGH on active byte lanes.
     */
    svt_err_check_stats invalid_low_mask_for_a_chnl_msg_error;

    /**
     * Check: Probe messages are never multi-beat, but must still drive mask HIGH on active byte lanes.
     */
    svt_err_check_stats invalid_low_mask_for_b_chnl_msg_error;

    /**
     * Check: Message PutFullData on channel_A must be responded with AccessAck on channel_D.
     */
    svt_err_check_stats msg_put_full_rsp_error;

    /**
     * Check: Message PutPartialData on channel_A must be responded with AccessAck on channel_D.
     */
    svt_err_check_stats msg_put_part_rsp_error;

    /**
     * Check: Message ArithmeticData on channel_A must be responded with AccessAckData on channel_D.
     */
    svt_err_check_stats msg_arithmetic_d_rsp_error;

    /**
     * Check: Message LogicalData on channel_A must be responded with AccessAckData on channel_D.
     */
    svt_err_check_stats msg_logical_d_rsp_error;

    /**
     * Check: Message Get on channel_A must be responded with AccessAckData on channel_D.
     */
    svt_err_check_stats msg_get_d_rsp_error;

    /**
     * Check: Message Intent on channel_A must be responded with HintAck on channel_D.
     */
    svt_err_check_stats msg_intent_i_rsp_error;

    /**
     * Check: Message AcquireBlock on channel_A must be responded with Grant/GrantData on channel_D.
     */
    svt_err_check_stats msg_acquire_blk_rsp_error;

    /**
     * Check: Message AcquirePerm on channel_A must be responded with Grant on channel_D.
     */
    svt_err_check_stats msg_acquire_perm_rsp_error;

    /**
     * Check: Message Grant/GrantData on channel_D must be responded with GrantAck on channel_E.
     */
    svt_err_check_stats msg_grant_rsp_error;

    /**
     * Check: Message Release/ReleaseData on channel_C must be responded with ReleaseAck on channel_D.
     */
    svt_err_check_stats msg_release_rsp_error;

    /**
     * Check: Message ProbeBlock on channel_B must be responded with ProbeAck/ProbeDataAck on channel_C.
     */
    svt_err_check_stats msg_probe_block_rsp_error;

    /**
     * Check: Message ProbePerm on channel_B must be responded with ProbeAck on channel_C.
     */
    svt_err_check_stats msg_probe_perm_rsp_error;

    /**
     * Check: Each inflight request identifier of channel-A in a particular link must be unique.
     */
    svt_err_check_stats identical_inflight_identifier_error;

    /**
     * Check: Each inflight request identifier of channel-B in a particular link must be unique.
     */
    svt_err_check_stats identical_inflight_identifier_chnl_B_error;

    /**
     * Check: Each inflight request identifier of channel-C in a particular link must be unique.
     */
    svt_err_check_stats identical_inflight_identifier_chnl_C_error;

    /**
     * Check: For all messages on A-channel, a_address must be aligned to a_size.
     */
    svt_err_check_stats a_address_not_alligned_to_a_size_error;

    /**
     * Check: For all messages on B-channel, b_address must be aligned to b_size.
     */
    svt_err_check_stats b_address_not_alligned_to_b_size_error;

    /**
     * Check: For all messages on C-channel, c_address must be aligned to c_size.
     */
    svt_err_check_stats c_address_not_alligned_to_c_size_error;

    /**
     * Check: For Get message on A-channel, a_corrupt is reserved and must be 0.
     */
    svt_err_check_stats rsvd_a_corrupt_value_in_a_chnl_msg_error;

    /**
     * Check: For Get message on B-channel, b_corrupt is reserved and must be 0, for Probe operation.
     */
    svt_err_check_stats rsvd_b_corrupt_value_in_b_chnl_msg_error;

    /**
     * Check: For Get message on C-channel, c_corrupt is reserved and must be 0, other than ProbeAckData,ReleaseData.
     */
    svt_err_check_stats rsvd_c_corrupt_value_in_c_chnl_msg_error;

